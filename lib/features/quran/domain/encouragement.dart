/// عبارات تشجيعية قصيرة لوضع الحفظ — ليست نصوصاً شرعية، بل تحفيز تربوي.
library;

/// مدح بعد تلاوة صحيحة (يُختار واحد بالتناوب).
const List<String> kidPraisePhrases = <String>[
  'ما شاء الله يا بطل! ⭐',
  'أحسنت يا بطل — أنت تقدر! 👏',
  'بارك الله فيك يا حافظ! 🌟',
  'ممتاز! الآية صحيحة تماماً ✅',
  'الله يبارك فيك، حفظ متقن! 🏅',
];

/// تشجيع بعد محاولة غير موفقة — يُعرض بعد «خطأ، حاول مرة أخرى» ([kidWrongMessage]).
const List<String> kidRetryPhrases = <String>[
  'أنت تقدر يا بطل! 💪',
  'اقرأ بهدوء وركّز، أنت قريب جداً 🌱',
  'كل الأبطال يخطئون ثم ينجحون 🌟',
  'خذ نفساً وابدأ من أول الآية 🍃',
  'استمع للآية مرة ثم جرّب، أنت ذكي! 🎧',
];

/// رسالة التلاوة الخاطئة للطفل: واضحة ثم مشجّعة.
String kidWrongMessage(int attempt) =>
    'خطأ، حاول مرة أخرى ❌ — ${pickPhrase(kidRetryPhrases, attempt)}';

/// لم يُسمع كلام واضح (صمت أو صوت بعيد).
const String kidNotHeardMessage =
    'لم أسمعك جيداً — اقترب من الهاتف واقرأ بصوت أوضح 🎤';

/// عبارات للكبار (أقل طفولية).
const List<String> adultPraisePhrases = <String>[
  'أحسنت — الآية صحيحة.',
  'بارك الله فيك، تلاوة صحيحة.',
  'ممتاز، واصل الحفظ.',
];

const List<String> adultRetryPhrases = <String>[
  'لم تتضح الآية — أعد المحاولة بصوت أوضح.',
  'حاول مرة أخرى، واقرأ الآية كاملة.',
];

/// يختار عبارة بالتناوب حسب رقم المحاولة (ثابت ليعمل في الاختبارات).
String pickPhrase(List<String> phrases, int attempt) =>
    phrases[attempt.abs() % phrases.length];
